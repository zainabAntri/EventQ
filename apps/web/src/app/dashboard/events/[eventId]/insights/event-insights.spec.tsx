import { beforeEach, describe, expect, it, vi } from 'vitest';
import { render, screen, within } from '@testing-library/react';
import type {
  AiStatusResponse,
  CategoryBreakdownResponse,
  EventInsightsResponse,
} from '@eventq/contracts';
import { ApiError } from '@/lib/api-client';
import { EventInsights } from './event-insights';

/**
 * Event Insights.
 *
 * The rule these tests protect is the one the page exists for: a measured
 * fact and an AI interpretation are never shown as the same kind of thing.
 * Facts live in one section that says nothing in it came from AI; anything
 * a model produced lives in a separate section under an "AI-generated" label,
 * with the model and the coverage beside it — and a failure on the AI side
 * never takes the facts down.
 */
const {
  getEventInsights,
  getEvent,
  getAiStatus,
  getCategoryBreakdown,
  listTopics,
  getLatestSummary,
  replace,
} = vi.hoisted(() => ({
  getEventInsights: vi.fn(),
  getEvent: vi.fn(),
  getAiStatus: vi.fn(),
  getCategoryBreakdown: vi.fn(),
  listTopics: vi.fn(),
  getLatestSummary: vi.fn(),
  replace: vi.fn(),
}));

vi.mock('@/lib/api-client/organizer', () => ({
  getEventInsights,
  getEvent,
  getAiStatus,
  getCategoryBreakdown,
  listTopics,
  getLatestSummary,
}));

vi.mock('next/navigation', () => ({
  useRouter: () => ({ replace, push: vi.fn(), refresh: vi.fn() }),
}));

const EVENT_ID = '01930000-0000-7000-8000-0000000000e1';
const id = (n: number) => `01930000-0000-7000-8000-${String(n).padStart(12, '0')}`;

